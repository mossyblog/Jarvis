    /// <summary>
    /// Gets version statistics for a resource.
    /// </summary>
    /// <param name="resourceEntityId">Resource entity ID</param>
    /// <returns>Version statistics</returns>
    public async Task<Dictionary<string, object>> GetVersionStats(Guid resourceEntityId)
    {
        var versions = await GetResourceVersions(resourceEntityId, true);
        
        return new Dictionary<string, object>
        {
            { "totalVersions", versions.Count },
            { "autoVersions", versions.Count(v => v.IsAutoGenerated) },
