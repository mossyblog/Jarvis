    /// <summary>
    /// Cleans up old versions based on retention policy.
    /// </summary>
    /// <param name="resourceEntityId">Resource entity ID</param>
    /// <param name="retentionPolicy">Retention policy configuration</param>
    /// <returns>Cleanup operation results</returns>
    public async Task<Dictionary<string, object>> CleanupOldVersions(Guid resourceEntityId, Dictionary<string, object> retentionPolicy)
    {
        var cleanedCount = 0;
        var retainedCount = 0;
        
        var versionsForCleanup = await GetVersionsForCleanup();
        var resourceVersions = versionsForCleanup.Where(v => v.ResourceEntityId == resourceEntityId).ToList();
        
        if (retentionPolicy.ContainsKey("olderThanDays") && retentionPolicy["olderThanDays"] is int olderThanDays)
        {
            var cutoffDate = DateTime.UtcNow.AddDays(-olderThanDays);
            var oldVersions = resourceVersions.Where(v => v.CreatedAt < cutoffDate).ToList();
            
            foreach (var version in oldVersions)
            {
                if (!version.IsPublished) // Don't delete published versions
                {
                    await DataContext.Remove<UIStudioVersion>(version.OwnerEntityId);
                    cleanedCount++;
                }
                else
                {
                    retainedCount++;
                }
            }
        }
        
        return new Dictionary<string, object>
        {
            { "cleanedCount", cleanedCount },
            { "retainedCount", retainedCount },
            { "policy", retentionPolicy }
        };
    }

