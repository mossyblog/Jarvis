    /// <summary>
    /// Validates the version configuration.
    /// </summary>
    /// <param name="version">Version to validate</param>
    /// <exception cref="ArgumentException">Thrown when validation fails</exception>
    private static void ValidateVersionConfiguration(UIStudioVersion version)
    {
        if (version.ResourceEntityId == Guid.Empty)
        {
            throw new ArgumentException("Resource entity ID is required");
        }

        if (string.IsNullOrWhiteSpace(version.ResourceType))
        {
            throw new ArgumentException("Resource type is required");
        }

        if (version.VersionNumber <= 0)
        {
            throw new ArgumentException("Version number must be greater than 0");
        }

        if (version.CreatedByEntityId == Guid.Empty)
        {
            throw new ArgumentException("Created by entity ID is required");
        }
    }

    /// <summary>
    /// Calculates SHA256 checksum for the given data.
    /// </summary>
    /// <param name="data">Data to calculate checksum for</param>
    /// <returns>Hexadecimal checksum string</returns>
    private static string CalculateChecksum(string data)
    {
        using var sha256 = SHA256.Create();
        var hashBytes = sha256.ComputeHash(Encoding.UTF8.GetBytes(data));
        return Convert.ToHexString(hashBytes).ToLowerInvariant();
    }
