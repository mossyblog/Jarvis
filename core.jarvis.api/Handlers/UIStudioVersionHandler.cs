    /// <summary>
    /// Compares two versions and generates a change summary.
    /// </summary>
    /// <param name="fromVersionNumber">Source version number</param>
    /// <param name="toVersionNumber">Target version number</param>
    /// <param name="resourceEntityId">Entity ID of the resource</param>
    /// <returns>Dictionary containing change information</returns>
    public async Task<Dictionary<string, object>?> CompareVersions(int fromVersionNumber, int toVersionNumber, Guid resourceEntityId)
    {
        var fromVersion = await GetVersion(resourceEntityId, fromVersionNumber);
        var toVersion = await GetVersion(resourceEntityId, toVersionNumber);

        if (fromVersion?.SnapshotData == null || toVersion?.SnapshotData == null)
        {
            return null;
        }

        // Basic comparison - can be enhanced with deep diff logic
        var changes = new Dictionary<string, object>
        {
            { "from_version", fromVersionNumber },
            { "to_version", toVersionNumber },
            { "from_checksum", fromVersion.SnapshotChecksum ?? "" },
            { "to_checksum", toVersion.SnapshotChecksum ?? "" },
            { "from_size", fromVersion.SnapshotSizeBytes },
            { "to_size", toVersion.SnapshotSizeBytes },
            { "has_changes", fromVersion.SnapshotChecksum != toVersion.SnapshotChecksum }
        };

        return changes;
    }

