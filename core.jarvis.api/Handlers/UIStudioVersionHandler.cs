    /// <summary>
    /// Creates a new version snapshot for a resource.
    /// </summary>
    /// <param name="version">The version snapshot to create</param>
    /// <returns>The created version component</returns>
    /// <exception cref="ArgumentException">Thrown when version configuration is invalid</exception>
    public async Task<UIStudioVersion> CreateVersion(UIStudioVersion version)
    {
        ValidateVersionConfiguration(version);
        
        // Calculate snapshot size and checksum if snapshot data is provided
        if (version.SnapshotData != null)
        {
            var jsonData = JsonSerializer.Serialize(version.SnapshotData);
            var versionWithMetadata = version with
            {
                SnapshotSizeBytes = Encoding.UTF8.GetByteCount(jsonData),
                SnapshotChecksum = CalculateChecksum(jsonData)
            };
            
            await DataContext.Commit(versionWithMetadata);
            return versionWithMetadata;
        }

        await DataContext.Commit(version);
        return version;
    }

    /// <summary>
    /// Creates an automatic version snapshot for a resource.
    /// </summary>
    /// <param name="resourceEntityId">Entity ID of the resource</param>
    /// <param name="resourceType">Type of the resource</param>
    /// <param name="snapshotData">Current state of the resource</param>
    /// <param name="createdByEntityId">Entity ID of the user creating the version</param>
    /// <param name="changeSummary">Summary of changes</param>
    /// <returns>The created version component</returns>
    public async Task<UIStudioVersion> CreateAutoVersion(
        Guid resourceEntityId, 
        string resourceType, 
        Dictionary<string, object> snapshotData,
        Guid createdByEntityId,
        string? changeSummary = null)
    {
        var nextVersionNumber = await GetNextVersionNumber(resourceEntityId);
        
        var jsonData = JsonSerializer.Serialize(snapshotData);
        var version = new UIStudioVersion
        {
            ResourceEntityId = resourceEntityId,
            ResourceType = resourceType,
            VersionNumber = nextVersionNumber,
            SnapshotData = snapshotData,
            CreatedByEntityId = createdByEntityId,
            IsAutoGenerated = true,
            ChangeSummary = changeSummary ?? $"Auto-generated version {nextVersionNumber}",
            SnapshotSizeBytes = Encoding.UTF8.GetByteCount(jsonData),
            SnapshotChecksum = CalculateChecksum(jsonData),
            RetentionPolicy = "auto_cleanup",
            DeleteAfter = DateTime.UtcNow.AddDays(30) // Auto-generated versions kept for 30 days
        };

        return await CreateVersion(version);
    }

