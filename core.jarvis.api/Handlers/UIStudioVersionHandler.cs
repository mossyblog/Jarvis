    /// <summary>
    /// Gets version history for a resource with pagination.
    /// </summary>
    /// <param name="resourceEntityId">Entity ID of the resource</param>
    /// <param name="limit">Maximum number of versions to return</param>
    /// <param name="offset">Number of versions to skip</param>
    /// <param name="includeAutoGenerated">Whether to include auto-generated versions</param>
    /// <returns>List of versions with pagination</returns>
    public async Task<List<UIStudioVersion>> GetVersionHistory(Guid resourceEntityId, int limit = 50, int offset = 0, bool includeAutoGenerated = true)
    {
        var query = DataContext.Query()
            .WithAll<UIStudioVersion>(v => v.ResourceEntityId == resourceEntityId);

        if (!includeAutoGenerated)
        {
            query = query.WithAll<UIStudioVersion>(v => !v.IsAutoGenerated);
        }

        var results = await query.ToEntityComponents();
        var versions = new List<UIStudioVersion>();

        foreach (var result in results)
        {
            var handler = DataContext.For<UIStudioVersionHandler>(result.Key);
            var version = await handler.Get();
            if (version != null)
            {
                versions.Add(version);
            }
        }

        return versions.OrderByDescending(v => v.VersionNumber)
                      .Skip(offset)
                      .Take(limit)
                      .ToList();
    }

    /// <summary>
    /// Gets the next version number for a resource.
    /// </summary>
    /// <param name="resourceEntityId">Entity ID of the resource</param>
    /// <returns>The next version number</returns>
    public async Task<int> GetNextVersionNumber(Guid resourceEntityId)
    {
        var latestVersion = await GetLatestVersion(resourceEntityId);
        return (latestVersion?.VersionNumber ?? 0) + 1;
    }

