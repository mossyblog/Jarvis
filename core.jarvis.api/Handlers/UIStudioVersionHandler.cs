    /// <summary>
    /// Gets all versions for a specific resource.
    /// </summary>
    /// <param name="resourceEntityId">Entity ID of the resource</param>
    /// <param name="includeAutoGenerated">Whether to include auto-generated versions</param>
    /// <returns>List of versions ordered by version number descending</returns>
    public async Task<List<UIStudioVersion>> GetResourceVersions(Guid resourceEntityId, bool includeAutoGenerated = true)
    {
        var query = DataContext.Query()
            .WithAll<UIStudioVersion>(v => v.ResourceEntityId == resourceEntityId);

        if (!includeAutoGenerated)
        {
            query = query.WithAll<UIStudioVersion>(v => !v.IsAutoGenerated);
        }

        var results = await query.ToEntityComponents();
        var versions = new List<UIStudioVersion>();

        foreach (var result in results)
        {
            var handler = DataContext.For<UIStudioVersionHandler>(result.Key);
            var version = await handler.Get();
            if (version != null)
            {
                versions.Add(version);
            }
        }

        return versions.OrderByDescending(v => v.VersionNumber).ToList();
    }

    /// <summary>
    /// Gets a specific version by resource and version number.
    /// </summary>
    /// <param name="resourceEntityId">Entity ID of the resource</param>
    /// <param name="versionNumber">Version number to retrieve</param>
    /// <returns>The version if found, null otherwise</returns>
    public async Task<UIStudioVersion?> GetVersion(Guid resourceEntityId, int versionNumber)
    {
        var query = DataContext.Query()
            .WithAll<UIStudioVersion>(v => v.ResourceEntityId == resourceEntityId && v.VersionNumber == versionNumber);

        var results = await query.ToEntityComponents();
        var versionEntity = results.FirstOrDefault();
        
        if (versionEntity.Key == Guid.Empty) return null;

        var handler = DataContext.For<UIStudioVersionHandler>(versionEntity.Key);
        return await handler.Get();
    }

    /// <summary>
    /// Gets the latest version for a resource.
    /// </summary>
    /// <param name="resourceEntityId">Entity ID of the resource</param>
    /// <param name="publishedOnly">Whether to only consider published versions</param>
    /// <returns>The latest version if found, null otherwise</returns>
    public async Task<UIStudioVersion?> GetLatestVersion(Guid resourceEntityId, bool publishedOnly = false)
    {
        var versions = await GetResourceVersions(resourceEntityId, !publishedOnly);
        
        if (publishedOnly)
        {
            return versions.Where(v => v.IsPublished).FirstOrDefault();
        }

        return versions.FirstOrDefault();
    }

